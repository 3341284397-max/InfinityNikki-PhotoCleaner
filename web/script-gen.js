  /**
   * 生成一段可以直接粘进 cmd 窗口的命令。
   *
   * 为什么需要它：下载下来的 .bat 带着网络标记，又顶着脚本扩展名，
   * 很容易被 Windows 安全中心直接拦掉，而复制现成的命令不落盘、
   * 没有文件可拦，是最省事的绕路办法。
   *
   * 交互式 cmd 里 %%F / goto / call 都不好使，所以这里把循环整个展开成一条条 move。
   * @returns {{text:string, filename:string}}
   */
  function buildCommands(lang, names, srcPath) {
    var isEn = lang === 'en';
    var L = TEXT[isEn ? 'en' : 'zh'];
    var list = cleanNames(names);
    var src = normPath(srcPath) || L.cmd.fallbackPath;
    var out = [];

    L.cmd.head.forEach(function (l) { out.push(l); });
    out.push('rem ' + new Array(61).join('-'));
    out.push('');
    out.push(L.cmd.cdNote);
    if (!isEn) out.push('chcp 936 >nul');
    out.push('cd /d "' + src + '"');
    out.push('if not exist "' + src + '\\." echo ' + L.cmd.badPath);
    out.push('md "' + L.folder + '" 2>nul');
    out.push('');

    list.forEach(function (n) {
      var dot = n.lastIndexOf('.');
      var stem = dot > 0 ? n.slice(0, dot) : n;
      var ext = dot > 0 ? n.slice(dot) : '';
      // 目标已有同名文件就改成 名字_1.扩展名，绝不覆盖
      out.push('if exist "' + L.folder + '\\' + n + '" ' +
        '(move "' + n + '" "' + L.folder + '\\' + stem + '_1' + ext + '") ' +
        'else (move "' + n + '" "' + L.folder + '")');
    });

    out.push('');
    out.push('echo ' + L.cmd.done);

    return {
      text: out.join('\r\n') + '\r\n',
      filename: isEn
        ? 'nikki-cleanup-commands-' + list.length + '.txt'
        : '清理照片命令-' + list.length + '张.txt'
    };
  }

  /**
   * 生成给用户自己的 AI 助手看的提示词 —— 前面两条路都走不通时的兜底。
   * 纯文本，粘给任何能操作文件的助手都能读懂。
   * @returns {{text:string, filename:string}}
   */
  function buildPrompt(lang, names, srcPath) {
    var isEn = lang === 'en';
    var L = TEXT[isEn ? 'en' : 'zh'];
    var P = L.pt;
    var list = cleanNames(names);
    var src = normPath(srcPath) || L.cmd.fallbackPath;
    var dst = src + '\\' + L.folder;
    var sep = isEn ? ': ' : '：';
    var out = [];

    out.push(P.title);
    out.push('');
    out.push(P.src + sep + src);
    out.push(P.dst + sep + dst + ' ' + P.dstNote);
    out.push('');
    out.push(fill(P.list, list.length));
    list.forEach(function (n, i) { out.push('  ' + (i + 1) + '. ' + n); });
    out.push('');
    out.push(P.rulesT);
    P.rules.forEach(function (r, i) { out.push('  ' + (i + 1) + '. ' + r); });
    out.push('');
    out.push(P.bgT + sep + P.bg);

    return {
      text: out.join('\r\n') + '\r\n',
      filename: isEn
        ? 'nikki-cleanup-prompt-' + list.length + '.txt'
        : '清理照片提示词-' + list.length + '张.txt'
    };
  }

  return {
    build: build,
    buildCommands: buildCommands,
    buildPrompt: buildPrompt,
    encodeGbk: encodeGbk,
    cleanNames: cleanNames
  };
