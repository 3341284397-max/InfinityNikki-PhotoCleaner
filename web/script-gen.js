/* ==========================================================================
   移动脚本生成器 —— 网页版「无限暖暖 · 照片清理助手」
   --------------------------------------------------------------------------
   把勾选的照片名编译成一个双击即用的 .bat：
   新建待清理文件夹 → 把照片移进去 → 问要不要删掉脚本自己。

   为什么单独一个文件：这段逻辑要能在 Node 里跑测试（见 test/ 目录），
   所以不依赖任何 DOM，只用 UMD 包一层。

   为什么中文脚本要写成 GBK：
   cmd 读批处理时按「当前代码页」逐行取字节。中文 Windows 默认 936，
   如果文件是 UTF-8，多字节字符会让 cmd 的行偏移算错，读到半行时
   会把半个句子当成命令去执行（实测会把「不要删掉自己」当命令跑）。
   GBK 与 936 一一对应，所以中文脚本一律按 GBK 落盘；英文脚本是纯 ASCII，
   任何代码页下都合法。
   ========================================================================== */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.NikkiScript = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* ---------------- GBK 编码 ---------------- */
  var gbkMap = null;

  /** 用 TextDecoder('gbk') 反向建表：字符 -> 双字节。表只建一次。 */
  function buildGbkMap() {
    var map = Object.create(null);
    var dec;
    try { dec = new TextDecoder('gbk'); } catch (e) { return null; }

    var buf = new Uint8Array(2);
    for (var lead = 0x81; lead <= 0xfe; lead++) {
      for (var trail = 0x40; trail <= 0xfe; trail++) {
        if (trail === 0x7f) continue;
        buf[0] = lead; buf[1] = trail;
        var ch = dec.decode(buf);
        // 只收单字符、且不是替换符；同一个字有多组编码时保留第一组
        if (ch.length === 1 && ch !== '\ufffd' && !(ch in map)) map[ch] = [lead, trail];
      }
    }
    return map;
  }

  /** 把字符串编成 GBK 字节。GBK 编不了的字退化成 '?'，不让整份脚本报废。 */
  function encodeGbk(text) {
    if (!gbkMap) gbkMap = buildGbkMap();
    var out = [];
    for (var i = 0; i < text.length; i++) {
      var ch = text.charAt(i);
      var code = text.charCodeAt(i);

      if (code < 0x80) { out.push(code); continue; }
      if (!gbkMap) { out.push(0x3f); continue; }

      var pair = gbkMap[ch];
      if (pair) { out.push(pair[0], pair[1]); continue; }
      out.push(0x3f);   // '?'
    }
    return new Uint8Array(out);
  }

  function encodeAscii(text) {
    var out = [];
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      out.push(c < 0x80 ? c : 0x3f);
    }
    return new Uint8Array(out);
  }

  /* ---------------- 文案 ---------------- */
  var TEXT = {
    zh: {
      folder: '无限暖暖清理助手_待清理照片',
      title: '无限暖暖 · 移动待清理照片',
      head: [
        'rem ============================================================',
        'rem 由网页版「无限暖暖 · 照片清理助手」生成。纯文本，右键记事本可以逐行核对。',
        'rem 它只做三件事：',
        'rem   1. 在截图文件夹里新建「无限暖暖清理助手_待清理照片」',
        'rem   2. 把下面列出的 {n} 张照片移进去',
        'rem   3. 问你要不要删掉这个脚本本身',
        'rem 不会删除任何一张照片。',
        'rem ============================================================'
      ],
      askPath: [
        'echo.',
        'echo   没有在脚本旁边找到截图文件夹。',
        'echo   把 X6Game\\ScreenShot 文件夹直接拖进这个窗口，然后按回车：',
        'echo.'
      ],
      prompt: '  路径: ',
      badPath: '  [x] 找不到这个文件夹：',
      srcLabel: '  截图文件夹  ',
      moved: '  已经移入待清理文件夹：!OK! 张',
      missed: '  跳过（原位置已经没有）：!MISS! 张',
      failed: '  失败（可能被占用）：!FAIL! 张',
      openIt: '  已打开待清理文件夹。确认无误后全选、按 Delete 删除。',
      nothing: '  没有移动任何照片。可能这些截图已经被移走，或者选错了文件夹。',
      askDel: '  要删掉这个一次性脚本吗？[Y 删掉 / 回车 留着]',
      askArrow: ' > ',
      deleted: '  已删除脚本。',
      bye: '  按任意键关闭窗口。',
      quit: ['  已中止，没有移动任何文件。', '  按任意键关闭窗口。'],
      moved1: '  已移动  '
    },
    en: {
      folder: 'NikkiCleaner_ToDelete',
      title: 'Infinity Nikki - move screenshots to review folder',
      head: [
        'rem ============================================================',
        'rem Generated by the web version of Infinity Nikki Photo Cleanup Assistant.',
        'rem Plain text - right-click and open in Notepad to read every line.',
        'rem It does three things only:',
        'rem   1. creates "NikkiCleaner_ToDelete" inside the screenshot folder',
        'rem   2. moves the {n} photos listed below into it',
        'rem   3. asks whether to delete this script itself',
        'rem It never deletes a photo.',
        'rem ============================================================'
      ],
      askPath: [
        'echo.',
        'echo   No screenshot folder was found next to this script.',
        'echo   Drag the X6Game\\ScreenShot folder into this window, then press Enter:',
        'echo.'
      ],
      prompt: '  Path: ',
      badPath: '  [x] Folder not found: ',
      srcLabel: '  Screenshot folder  ',
      moved: '  Moved into the review folder: !OK!',
      missed: '  Skipped (no longer in place): !MISS!',
      failed: '  Failed (file may be locked): !FAIL!',
      openIt: '  Opened the review folder. Check the photos, then select all and press Delete.',
      nothing: '  Nothing was moved. The screenshots may already be gone, or the folder is wrong.',
      askDel: '  Delete this one-time script? [Y delete / Enter keep]',
      askArrow: ' > ',
      deleted: '  Script deleted.',
      bye: '  Press any key to close.',
      quit: ['  Stopped. Nothing was moved.', '  Press any key to close.'],
      moved1: '  moved  '
    }
  };

  /* ---------------- 生成 ---------------- */
  function fill(s, n) { return s.replace(/\{n\}/g, n); }

  /**
   * @param {'zh'|'en'} lang
   * @param {string[]} names 勾选的照片文件名（只写文件名，不含路径）
   * @returns {{filename:string, text:string, bytes:Uint8Array, encoding:string}}
   */
  function build(lang, names) {
    var L = TEXT[lang === 'en' ? 'en' : 'zh'];
    var list = (names || []).filter(function (n) { return /^[^\\/:*?"<>|]+$/.test(n); });
    var mark = list[0] || '';

    var out = [];
    function add(s) { out.push(s); }

    add('@echo off');
    if (lang !== 'en') add('chcp 936 >nul');
    add('setlocal enabledelayedexpansion');
    add('title ' + L.title);
    add('');

    L.head.forEach(function (line) { add(fill(line, list.length)); });
    add('');

    add('set "PENDING=' + L.folder + '"');
    add('set "MARK=' + mark + '"');
    add('set "SRC="');
    add('');

    add('rem 脚本放在 ScreenShot 里最省事；放别处也行，下面会问一句');
    add('for %%P in ("%~dp0.") do if /i "%%~nxP"=="ScreenShot" set "SRC=%~dp0"');
    add('if not defined SRC if exist "%~dp0%MARK%" set "SRC=%~dp0"');
    add('if not defined SRC if exist "%~dp0ScreenShot\\%MARK%" set "SRC=%~dp0ScreenShot\\"');
    add('');

    add('if not defined SRC (');
    L.askPath.forEach(function (line) { add('  ' + line); });
    add('  set /p "SRC=' + L.prompt + '"');
    add(')');
    add('');

    add('if not defined SRC goto :quit');
    add('for /f "delims=" %%A in ("!SRC!") do set "SRC=%%~A"');
    add('if not "!SRC:~-1!"=="\\" set "SRC=!SRC!\\"');
    add('if not exist "!SRC!" (');
    add('  echo.');
    add('  echo ' + L.badPath + '!SRC!');
    add('  goto :quit');
    add(')');
    add('');

    add('echo.');
    add('echo ' + L.srcLabel + '!SRC!');
    add('echo.');
    add('');

    add('set /a OK=0');
    add('set /a MISS=0');
    add('set /a FAIL=0');
    add('');
    add('for %%F in (');
    list.forEach(function (n) { add('"' + n + '"'); });
    add(') do call :one %%F');
    add('');

    add('echo.');
    add('if !OK! gtr 0 echo ' + L.moved);
    add('if !MISS! gtr 0 echo ' + L.missed);
    add('if !FAIL! gtr 0 echo ' + L.failed);
    add('echo.');
    add('if !OK! gtr 0 (');
    add('  start "" "!SRC!%PENDING%"');
    add('  echo ' + L.openIt);
    add(') else (');
    add('  echo ' + L.nothing);
    add(')');
    add('');

    add('set "ANS="');
    add('echo.');
    add('echo ' + L.askDel);
    add('set /p "ANS=' + L.askArrow + '"');
    add('set "DELIT=0"');
    add('if /i "!ANS!"=="Y" set "DELIT=1"');
    add('');
    add('echo.');
    add('echo ' + L.bye);
    add('pause >nul');
    add('if not "!DELIT!"=="1" exit /b');
    add('(goto) 2>nul & del "%~f0"');
    add('');

    add(':one');
    add('set "NAME=%~1"');
    add('if not exist "!SRC!!NAME!" (');
    add('  set /a MISS+=1');
    add('  goto :eof');
    add(')');
    add('set "TO=!SRC!%PENDING%\\!NAME!"');
    add('if not exist "!SRC!%PENDING%" md "!SRC!%PENDING%"');
    add('set "i=0"');
    add('for /l %%k in (1,1,50) do (');
    add('  if exist "!TO!" (');
    add('    set /a i+=1');
    add('    set "TO=!SRC!%PENDING%\\%~n1_!i!%~x1%"');
    add('  )');
    add(')');
    add('move /y "!SRC!!NAME!" "!TO!" >nul 2>&1');
    add('if errorlevel 1 (');
    add('  set /a FAIL+=1');
    add('  goto :eof');
    add(')');
    add('set /a OK+=1');
    add('echo ' + L.moved1 + '!NAME!');
    add('goto :eof');
    add('');

    add(':quit');
    L.quit.forEach(function (line) { add('  ' + line); });
    add('pause >nul');
    add('exit /b');

    var text = out.join('\r\n') + '\r\n';
    var isEn = lang === 'en';

    return {
      filename: isEn
        ? 'nikki-cleanup-' + list.length + '.bat'
        : '清理照片-' + list.length + '张.bat',
      text: text,
      bytes: isEn ? encodeAscii(text) : encodeGbk(text),
      encoding: isEn ? 'ascii' : 'gbk'
    };
  }

  return { build: build, encodeGbk: encodeGbk };
});
