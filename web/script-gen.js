  var gbkMap = null;

  /** 用 TextDecoder('gbk') 反向建表：字符 -> 双字节。表只建一次。 */
  function buildGbkMap() {
    var map = Object.create(null);
    var dec;
    try { dec = new TextDecoder('gbk'); } catch (e) { return null; }

    var buf = new Uint8Array(2);
    for (var lead = 0x81; lead <= 0xfe; lead++) {
      for (var trail = 0x40; trail <= 0xfe; trail++) {
        if (trail === 0x7f) continue;
        buf[0] = lead; buf[1] = trail;
        var ch = dec.decode(buf);
        // 只收单字符、且不是替换符；同一个字有多组编码时保留第一组
        if (ch.length === 1 && ch !== '\ufffd' && !(ch in map)) map[ch] = [lead, trail];
      }
    }
    return map;
  }

  /** 把字符串编成 GBK 字节。GBK 编不了的字退化成 '?'，不让整份脚本报废。 */
  function encodeGbk(text) {
    if (!gbkMap) gbkMap = buildGbkMap();
    var out = [];
    for (var i = 0; i < text.length; i++) {
      var ch = text.charAt(i);
      var code = text.charCodeAt(i);

      if (code < 0x80) { out.push(code); continue; }
      if (!gbkMap) { out.push(0x3f); continue; }

      var pair = gbkMap[ch];
      if (pair) { out.push(pair[0], pair[1]); continue; }
      out.push(0x3f);   // '?'
    }
    return new Uint8Array(out);
  }

  function encodeAscii(text) {
    var out = [];
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      out.push(c < 0x80 ? c : 0x3f);
    }
    return new Uint8Array(out);
  }

