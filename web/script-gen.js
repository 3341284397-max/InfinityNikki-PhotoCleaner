    add('@echo off');
    if (lang !== 'en') add('chcp 936 >nul');
    add('setlocal enabledelayedexpansion');
    add('title ' + L.title);
    add('');

    L.head.forEach(function (line) { add(fill(line, list.length)); });
    add('');

